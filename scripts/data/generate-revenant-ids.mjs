import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { SKILLS, SPECIALIZATIONS } from '#gw2/professions/revenant/data/revenant-api-metadata.js';
import { REVENANT_SUPPLEMENTAL_SKILLS } from '#gw2/professions/revenant/data/revenant-supplemental-skills.js';
import { declaration, stableEntries } from './lib/generator-utils.mjs';

// Disambiguate Nature by legend so regenerating API IDs preserves readable mechanic references.
const skillNames = {
  51667: 'True Nature Assassin',
  51675: 'True Nature Dwarf',
  51696: 'True Nature Dragon',
  51713: 'True Nature Centaur',
  51714: 'True Nature Demon'
};
const skills = stableEntries([
  ...SKILLS.map((skill) => [skillNames[skill.id] ?? skill.name, skill.id]),
  ...REVENANT_SUPPLEMENTAL_SKILLS.map((skill) => [skill.name, skill.id])
]);
const traits = stableEntries(
  SPECIALIZATIONS.flatMap((specialization) => [
    ...specialization.minorTraits,
    ...specialization.majorTraits.flat()
  ]).map((trait) => [trait.name, trait.id])
);
const output = [
  '// Generated by scripts/data/generate-revenant-ids.mjs.',
  '// Committed constants keep mechanic references stable across metadata loads.',
  '',
  declaration('REVENANT_SKILL_IDS', skills, ['SWAP_WEAPONS: -3,', 'SWAP_LEGENDS: -4,', 'DODGE: -5,']),
  '',
  declaration('REVENANT_TRAIT_IDS', traits),
  '',
  `export const REVENANT_LEGEND_IDS = Object.freeze({
  ASSASSIN: "LegendaryAssassin",
  DEMON: "LegendaryDemon",
  DWARF: "LegendaryDwarf",
  CENTAUR: "LegendaryCentaur",
  DRAGON: "LegendaryDragon",
  RENEGADE: "LegendaryRenegade",
  ALLIANCE: "LegendaryAlliance",
  ENTITY: "LegendaryEntity",
});`,
  ''
].join('\n');

// Writes TypeScript ID constants after the package command compiles and loads
// the generated snapshot through the standard test/tooling resolver.
const target = fileURLToPath(new URL('../../js/games/gw2/professions/revenant/data/ids.ts', import.meta.url));

await writeFile(target, output, 'utf8');
