import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { declaration, stableEntries } from './lib/generator-utils.mjs';
import { fetchGw2Api, fetchManyGw2 } from './lib/gw2-profession-snapshot.mjs';

const SUPPLEMENTAL_SKILLS = [
  ['Twin Darts', 12676],
  ['Pet Tail Lash', 12673],
  ['Crippling Anguish Pet', 41864],
  ['Consuming Bite', 43734],
  ['Narcotic Spores Pet', 45262],
  ['Spit', 12724],
  ['Cosmic Ray', 31796],
  ['Seed of Life', 31406],
  ['Lunar Impact', 31318],
  ['Rejuvenating Tides', 31894],
  ['Natural Convergence', 31503],
  ['Keen Shot', 77183],
  ['Hawkeye', 76664],
  ['Bluster', 77319],
  ['Fleeting Zephyr', 77012],
  ["Quarry's Peril", 76807],
  ['Pelt', 76722],
  ['Supersonic Arrow', 77174],
  ['Wuthering Wind', 76905]
];

// Fetches all ranger pet skills from the GW2 API, returning an array of skill objects.
async function rangerPetSkills() {
  const petIds = await fetchGw2Api('/pets');
  const pets = await fetchManyGw2('pets', petIds, { preserveIdOrder: true });

  // Keep White Moa's Icy Screech out of generated constants as well as the pet catalog.
  const ids = [...new Set(pets.filter((pet) => pet.id !== 14).flatMap((pet) => pet.skills.map((skill) => skill.id)))];
  return fetchManyGw2('skills', ids, { preserveIdOrder: true });
}

// Generates only consumed skill and trait IDs from the freshly fetched snapshot so the update
// pipeline does not need to execute the generated TypeScript module first.
export async function generateRangerIds({ skills: apiSkills, specializations: apiSpecializations }) {
  const petSkills = await rangerPetSkills();
  const skills = stableEntries([
    ...apiSkills.filter((skill) => ![-3, -5].includes(Number(skill.id))).map((skill) => [skill.name, skill.id]),
    ...petSkills.map((skill) => [skill.name, skill.id]),
    ...SUPPLEMENTAL_SKILLS
  ]);
  const traits = stableEntries(
    apiSpecializations
      .flatMap((specialization) => [...specialization.minorTraits, ...specialization.majorTraits.flat()])
      .map((trait) => [trait.name, trait.id])
  );

  const source = [
    '// Generated by scripts/data/generate-ranger-ids.mjs.',
    '// Committed constants keep mechanic references independent from metadata loading.',
    '',
    declaration('RANGER_SKILL_IDS', skills),
    '',
    declaration('RANGER_TRAIT_IDS', traits),
    ''
  ].join('\n');

  const target = fileURLToPath(new URL('../../js/games/gw2/professions/ranger/data/ids.ts', import.meta.url));

  await writeFile(target, source, 'utf8');
  console.log(`Wrote ${skills.length} skill and ${traits.length} trait IDs.`);
}
