async function fetchJson(pathname) {
  const response = await fetch(
    `https://api.guildwars2.com/v2${pathname}${pathname.includes("?") ? "&" : "?"}lang=en`,
  );
  if (!response.ok) throw new Error(`${response.status} ${pathname}`);
  return response.json();
}

async function rangerPetSkills() {
  const petIds = await fetchJson("/pets");
  const pets = [];
  for (let index = 0; index < petIds.length; index += 100) {
    pets.push(
      ...(await fetchJson(
        `/pets?ids=${petIds.slice(index, index + 100).join(",")}`,
      )),
    );
  }
  const ids = [
    ...new Set(pets.flatMap((pet) => pet.skills.map((skill) => skill.id))),
  ];
  const skills = [];
  for (let index = 0; index < ids.length; index += 100) {
    skills.push(
      ...(await fetchJson(
        `/skills?ids=${ids.slice(index, index + 100).join(",")}`,
      )),
    );
  }
  return skills;
}

function constantName(value) {
  return String(value || "")
    .normalize("NFKD")
    .replace(/['\u2019]/g, "")
    .replace(/[^a-z0-9]+/gi, "_")
    .replace(/^_+|_+$/g, "")
    .toUpperCase();
}

function stableEntries(entries) {
  const result = [];
  const keys = new Set();
  for (const [name, id] of entries) {
    const base = constantName(name);
    if (!base) continue;
    const key = keys.has(base) ? `${base}_ID_${id}` : base;
    keys.add(base);
    result.push({ key, id: Number(id), name: String(name) });
  }
  return result;
}

function declaration(name, entries, prefix = []) {
  return [
    `export const ${name} = Object.freeze({`,
    ...prefix.map((line) => `  ${line}`),
    ...entries.map((entry) => `  ${entry.key}: ${entry.id}, // ${entry.name}`),
    "});",
  ].join("\n");
}

const petSkills = await rangerPetSkills();
const skills = stableEntries([
  ...SKILLS.map((skill) => [skill.name, skill.id]),
  ...petSkills.map((skill) => [skill.name, skill.id]),
  ...SUPPLEMENTAL_SKILLS,
]);
const traits = stableEntries(
  SPECIALIZATIONS.flatMap((specialization) => [
    ...specialization.minorTraits,
    ...specialization.majorTraits.flat(),
  ]).map((trait) => [trait.name, trait.id]),
);
const specializations = SPECIALIZATIONS.map((specialization) => ({
  key: constantName(specialization.name),
  id: Number(specialization.id),
  name: specialization.name,
}));

const source = [
  "// Generated by scripts/data/generate-ranger-ids.mjs.",
  "// Committed constants keep mechanic references independent from metadata loading.",
  "",
  declaration("RANGER_SKILL_IDS", skills, ["SWAP_WEAPONS: -3,"]),
  "",
  declaration("RANGER_TRAIT_IDS", traits),
  "",
  declaration("RANGER_SPECIALIZATION_IDS", specializations),
  "",
].join("\n");

const target = fileURLToPath(
  new URL("../../js/professions/ranger/data/ids.ts", import.meta.url),
);
await writeFile(target, source, "utf8");
console.log(
  `Wrote ${skills.length} skill, ${traits.length} trait, and ${specializations.length} specialization IDs.`,
);
