import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { SKILLS, SPECIALIZATIONS } from '#gw2/professions/engineer/data/engineer-api-metadata.js';
import { ENGINEER_SUPPLEMENTAL_SKILLS } from '#gw2/professions/engineer/data/engineer-supplemental-skills.js';
import { declaration, stableEntries } from './lib/generator-utils.mjs';

// Distinguish non-Holosmith sword variants that share API names with Holosmith skills.
const NON_HOLOSMITH_SWORD_IDS = new Set([69565, 69906, 70514, 70771, 71121]);
const skills = stableEntries([
  ...SKILLS.map((skill) => [
    NON_HOLOSMITH_SWORD_IDS.has(Number(skill.id)) ? `${skill.name} Non Holosmith` : skill.name,
    skill.id
  ]),
  ...ENGINEER_SUPPLEMENTAL_SKILLS.map((skill) => [skill.name, skill.id])
]);
const traits = stableEntries(
  SPECIALIZATIONS.flatMap((specialization) => [
    ...specialization.minorTraits,
    ...specialization.majorTraits.flat()
  ]).map((trait) => [trait.name, trait.id])
);
// Synthetic actions have no API identity, and the API names both Evolve variants "Evolve"; semantic IDs distinguish
// the trait-selected actions.
const fixedSkillIds = [
  'SWAP_WEAPONS: -3,',
  'DODGE: -5,',
  'STOW_ELITE_MORTAR_KIT: -301,',
  'EVOLVE_BASE: 76642,',
  'EVOLVE_DOUBLE_HELIX: 76651,'
];
// A frozen object literal rejects repeated keys, so fail generation instead of emitting shadowed constants.
function assertUniqueKeys(name, keys) {
  const seen = new Set();
  const duplicates = keys.filter((key) => seen.has(key) || !seen.add(key));
  if (duplicates.length) throw new Error(`${name} has duplicate generated keys: ${duplicates.join(', ')}`);
}

assertUniqueKeys('ENGINEER_SKILL_IDS', [
  ...fixedSkillIds.map((line) => line.split(':')[0]),
  ...skills.map((entry) => entry.key)
]);
assertUniqueKeys(
  'ENGINEER_TRAIT_IDS',
  traits.map((entry) => entry.key)
);

const output = [
  '// Generated by scripts/data/generate-engineer-ids.mjs.',
  '// Committed constants keep mechanic references stable across metadata loads.',
  '',
  declaration('ENGINEER_SKILL_IDS', skills, fixedSkillIds),
  '',
  declaration('ENGINEER_TRAIT_IDS', traits),
  ''
].join('\n');

// Writes TypeScript ID constants after the package command compiles and loads
// the generated snapshot through the standard test/tooling resolver.
const target = fileURLToPath(new URL('../../js/games/gw2/professions/engineer/data/ids.ts', import.meta.url));

await writeFile(target, output, 'utf8');
